"""Small synthetic fixed-codec baseline; Python stdlib only, no seed search.

Run from any directory. Outputs are exclusive to a new run ID. Large generated
files stay in research/local/; configuration, logs and measurements are tracked.
"""

import argparse
import hashlib
import json
import os
from pathlib import Path
import platform
import shutil
import statistics
import subprocess
import sys
import time
from datetime import datetime
from zoneinfo import ZoneInfo

ROOT = Path(__file__).resolve().parents[2]


def save(path, value):
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def digest(path):
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def snapshot(directory):
    return {p.relative_to(directory).as_posix(): (p.stat().st_size, digest(p))
            for p in sorted(directory.rglob("*")) if p.is_file()}


def invoke(command, log, timeout):
    start = time.perf_counter()
    try:
        result = subprocess.run(command, capture_output=True, timeout=timeout, check=False)
    except subprocess.TimeoutExpired as error:
        log.write_text(str(error), encoding="utf-8")
        raise RuntimeError(f"command exceeded {timeout}s: {command}") from error
    elapsed = time.perf_counter() - start
    log.write_bytes(result.stdout + b"\n--- stderr ---\n" + result.stderr)
    if result.returncode:
        raise RuntimeError(f"exit {result.returncode}; see {log}")
    return elapsed


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cli", required=True, type=Path)
    parser.add_argument("--run-id", required=True)
    parser.add_argument("--repetitions", type=int, default=3)
    args = parser.parse_args()
    if (not args.run_id or any(c not in "abcdefghijklmnopqrstuvwxyz0123456789-" for c in args.run_id)
            or len(args.run_id) > 100 or not 1 <= args.repetitions <= 10):
        parser.error("run-id must use lowercase ASCII/digits/hyphens; repetitions must be 1..10")
    source_cli = args.cli.resolve(strict=True)
    run = ROOT / "research/experiments" / args.run_id
    local = ROOT / "research/local" / args.run_id
    if run.exists() or local.exists():
        parser.error("run ID exists; choose a new ID (old evidence is never overwritten)")
    run.mkdir(parents=True)
    local.mkdir(parents=True)
    cli = local / source_cli.name
    shutil.copy2(source_cli, cli)
    shutil.copy2(__file__, run / "m3_baseline.py")
    config = {"run_id": args.run_id, "repetitions": args.repetitions,
              "build_type": "Release (caller-supplied; see build provenance in record.md)",
              "codecs": ["store", "zstd", "lzma2"], "levels": {"zstd": 3, "lzma2": 6},
              "chunk_bytes": 1048576, "threads": 1, "timeout_per_command_seconds": 120,
              "seed": None, "strategy_version": 0, "archive_revision": 1,
              "peak_memory_bytes": None, "memory_note": "not measured",
              "timing": "whole subprocess wall time; includes startup and integrity self-checks",
              "cache_policy": "no warmup; OS caches uncontrolled; rotate codec order each repetition",
              "scope": "synthetic exploration only; no independent evaluation or media corpus",
              "cli_sha256": digest(cli), "script_sha256": digest(Path(__file__)),
              "started_at": datetime.now(ZoneInfo("America/Los_Angeles")).isoformat(),
              "invocation": [sys.executable, *sys.argv], "working_directory": str(Path.cwd()),
              "python": sys.version, "os": platform.platform(), "cpu": platform.processor(),
              "logical_cpus": os.cpu_count()}
    version = subprocess.run([str(cli), "--version"], capture_output=True, check=True)
    config["cli_version"] = version.stdout.decode("utf-8", errors="replace").strip()
    config["git_commit"] = subprocess.check_output(["git", "-C", str(ROOT), "rev-parse", "HEAD"], text=True).strip()
    config["git_status"] = subprocess.check_output(["git", "-C", str(ROOT), "status", "--porcelain"], text=True)
    save(run / "config.json", config)
    # Reproducible, original synthetic fixtures: repeated text and SHA-256 counter bytes.
    text = (b"SeedArc synthetic baseline: fixed chunks and explicit codec choices.\n" * 4096)[:262144]
    noise = b"".join(hashlib.sha256(b"seedarc-m3-baseline-r1:" + i.to_bytes(8, "little")).digest()
                     for i in range(8192))
    datasets = {"text": {"text.txt": text}, "noise": {"noise.bin": noise},
                "mixed": {"text.txt": text, "sub/noise.bin": noise, "empty": b""}}
    manifest = {"id": "synthetic-m3-r1", "source": "generated by accompanying script",
                "license": "GPL-3.0-or-later (project-authored synthetic fixtures)",
                "usage": "exploration, not training or independent evaluation", "datasets": {}}
    for name, files in datasets.items():
        directory = local / "inputs" / name
        for relative, data in files.items():
            path = directory / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        manifest["datasets"][name] = snapshot(directory)
    save(run / "datasets.json", manifest)
    config["dataset_manifest_sha256"] = digest(run / "datasets.json")
    save(run / "config.json", config)
    results = []
    try:
        for repeat in range(args.repetitions):
            order = config["codecs"][repeat % 3:] + config["codecs"][:repeat % 3]
            for dataset in datasets:
                for codec in order:
                    label = f"{repeat}-{dataset}-{codec}"
                    archive, output = local / f"{label}.sarc", local / f"{label}-out"
                    input_dir = local / "inputs" / dataset
                    compress = [str(cli), "compress", str(input_dir), "-o", str(archive), "--codec", codec]
                    if codec != "store":
                        compress += ["--level", str(config["levels"][codec])]
                    commands = [compress, [str(cli), "verify", str(archive)],
                                [str(cli), "extract", str(archive), "-o", str(output)]]
                    row = {"repeat": repeat, "dataset": dataset, "codec": codec,
                           "commands": commands, "status": "running", "peak_memory_bytes": None,
                           "candidate_count": 1, "search_seconds": None}
                    results.append(row)
                    try:
                        for operation, command in zip(["compress", "verify", "extract"], commands):
                            row[f"{operation}_seconds"] = invoke(command, run / f"{label}-{operation}.log", 120)
                        row["archive_bytes"] = archive.stat().st_size
                        row["archive_sha256"] = digest(archive)
                        row["input_bytes"] = sum(len(b) for b in datasets[dataset].values())
                        row["byte_exact"] = snapshot(input_dir) == snapshot(output)
                        if not row["byte_exact"]:
                            raise RuntimeError(f"round-trip mismatch: {label}")
                        row["status"] = "passed"
                    except Exception as error:
                        row["status"], row["error"] = "failed", str(error)
                        raise
                    finally:
                        save(run / "raw.json", results)
                    print(label, row["archive_bytes"], "byte-exact", flush=True)
        summary = []
        for dataset in datasets:
            for codec in config["codecs"]:
                rows = [r for r in results if r["dataset"] == dataset and r["codec"] == codec]
                summary.append({"dataset": dataset, "codec": codec,
                                "archive_bytes": sorted({r["archive_bytes"] for r in rows}),
                                "archive_sha256": sorted({r["archive_sha256"] for r in rows}),
                                "median_compress_seconds": statistics.median(r["compress_seconds"] for r in rows),
                                "all_byte_exact": all(r["byte_exact"] for r in rows)})
        save(run / "summary.json", summary)
        config["status"] = "completed"
    except Exception as error:
        config["status"], config["error"] = "failed", str(error)
        raise
    finally:
        config["finished_at"] = datetime.now(ZoneInfo("America/Los_Angeles")).isoformat()
        save(run / "config.json", config)


if __name__ == "__main__":
    main()
