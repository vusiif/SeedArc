"""Generate core/filesystem/unicode_tables.inc from the pinned Unicode Character Database.

The archive path profile (ADR-0005) needs four Unicode properties, all from one pinned UCD
version so that every platform answers the same way:

  * assigned code points        UnicodeData.txt (with <..., First>/<..., Last> ranges)
  * canonical combining class   UnicodeData.txt field 3
  * canonical decomposition     UnicodeData.txt field 5 (no <tag>), fully expanded here
  * canonical composition       the length-2 canonical decompositions whose composite is not
                                Full_Composition_Exclusion (DerivedNormalizationProps.txt)
  * simple case folding         CaseFolding.txt, status C and S

Hangul syllables are algorithmic and therefore not in the tables.

Usage:  python -I unicode_tables_gen.py <ucd-dir> <output.inc>
        python -I unicode_tables_gen.py <ucd-dir> <output.inc> --check   (exit 1 if stale)
Standard library only.
"""

import hashlib
import pathlib
import sys

INPUTS = ("UnicodeData.txt", "DerivedNormalizationProps.txt", "CaseFolding.txt")
HANGUL_FIRST, HANGUL_LAST = 0xAC00, 0xD7A3


def data_lines(path):
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.split("#", 1)[0].strip()
        if line:
            yield line


def parse_unicode_data(path):
    assigned, ccc, decomposition = [], {}, {}
    pending_first = None
    for line in data_lines(path):
        fields = line.split(";")
        cp = int(fields[0], 16)
        name = fields[1]
        if name.endswith(", First>"):
            pending_first = cp
            continue
        if name.endswith(", Last>"):
            if pending_first is None:
                raise ValueError(f"range end without start at {cp:04X}")
            assigned.append((pending_first, cp))
            pending_first = None
            continue
        assigned.append((cp, cp))
        if int(fields[3]) != 0:
            ccc[cp] = int(fields[3])
        if fields[5] and not fields[5].startswith("<"):
            decomposition[cp] = [int(x, 16) for x in fields[5].split()]
    if pending_first is not None:
        raise ValueError("unterminated range")
    return assigned, ccc, decomposition


def merge_ranges(ranges):
    merged = []
    for lo, hi in sorted(ranges):
        if merged and lo <= merged[-1][1] + 1:
            merged[-1] = (merged[-1][0], max(merged[-1][1], hi))
        else:
            merged.append((lo, hi))
    return merged


def parse_full_composition_exclusion(path):
    excluded = set()
    for line in data_lines(path):
        fields = [f.strip() for f in line.split(";")]
        if len(fields) >= 2 and fields[1] == "Full_Composition_Exclusion":
            if ".." in fields[0]:
                lo, hi = (int(x, 16) for x in fields[0].split(".."))
            else:
                lo = hi = int(fields[0], 16)
            excluded.update(range(lo, hi + 1))
    return excluded


def parse_case_folding(path):
    folds = {}
    for line in data_lines(path):
        fields = [f.strip() for f in line.split(";")]
        if fields[1] in ("C", "S"):
            folds[int(fields[0], 16)] = int(fields[2], 16)
    return folds


def full_decomposition(cp, decomposition):
    if cp not in decomposition:
        return [cp]
    out = []
    for part in decomposition[cp]:
        out.extend(full_decomposition(part, decomposition))
    return out


def render(ucd):
    digests = {name: hashlib.sha256((ucd / name).read_bytes()).hexdigest() for name in INPUTS}
    readme = (ucd / "ReadMe.txt").read_text(encoding="utf-8")
    version = "17.0.0"
    if f"Version {version}" not in readme:
        raise ValueError(f"{ucd}/ReadMe.txt does not describe Unicode {version}")

    assigned, ccc, decomposition = parse_unicode_data(ucd / "UnicodeData.txt")
    assigned = merge_ranges(assigned)
    excluded = parse_full_composition_exclusion(ucd / "DerivedNormalizationProps.txt")
    folds = parse_case_folding(ucd / "CaseFolding.txt")

    pool, decomp_rows = [], []
    for cp in sorted(decomposition):
        if HANGUL_FIRST <= cp <= HANGUL_LAST:
            continue
        full = full_decomposition(cp, decomposition)
        decomp_rows.append((cp, len(pool), len(full)))
        pool.extend(full)
    if len(pool) > 0xFFFF or max(r[2] for r in decomp_rows) > 0xFF:
        raise ValueError("decomposition pool does not fit the table types")

    compose_rows = sorted(
        (parts[0], parts[1], cp)
        for cp, parts in decomposition.items()
        if len(parts) == 2 and cp not in excluded
    )

    out = []
    w = out.append
    w("// SPDX-License-Identifier: GPL-3.0-or-later")
    w("// GENERATED by core/filesystem/unicode_tables_gen.py -- do not edit by hand.")
    w(f"// Source: Unicode Character Database {version}, third_party/unicode-ucd/{version}/")
    for name in INPUTS:
        w(f"//   {name} sha256 {digests[name]}")
    w("// Unicode data is under the Unicode License v3 (third_party/unicode-ucd/17.0.0/license.txt).")
    w("// Included only by core/filesystem/unicode_profile.cpp, inside its table namespace.")
    w("")
    w(f'inline constexpr std::string_view ucd_version = "{version}";')
    w("")

    def table(decl, rows, fmt, per_line=4):
        w(f"inline constexpr {decl}[] = {{")
        for i in range(0, len(rows), per_line):
            w("    " + " ".join(fmt(r) + "," for r in rows[i:i + per_line]))
        w("};")
        w("")

    table("CodeRange assigned_ranges", assigned,
          lambda r: f"{{0x{r[0]:04X}, 0x{r[1]:04X}}}")
    table("CombiningClass combining_classes", sorted(ccc.items()),
          lambda r: f"{{0x{r[0]:04X}, {r[1]}}}", 6)
    table("Decomposition decompositions", decomp_rows,
          lambda r: f"{{0x{r[0]:04X}, {r[1]}, {r[2]}}}", 5)
    table("char32_t decomposition_pool", pool, lambda r: f"0x{r:04X}", 10)
    table("Composition compositions", compose_rows,
          lambda r: f"{{0x{r[0]:04X}, 0x{r[1]:04X}, 0x{r[2]:04X}}}", 4)
    table("SimpleFold simple_folds", sorted(folds.items()),
          lambda r: f"{{0x{r[0]:04X}, 0x{r[1]:04X}}}", 5)
    return "\n".join(out)


def main(argv):
    if len(argv) not in (3, 4) or (len(argv) == 4 and argv[3] != "--check"):
        print(__doc__, file=sys.stderr)
        return 2
    ucd, target = pathlib.Path(argv[1]), pathlib.Path(argv[2])
    text = render(ucd)
    if len(argv) == 4:
        current = target.read_text(encoding="utf-8").replace("\r\n", "\n") if target.exists() else ""
        if current.rstrip("\n") != text.rstrip("\n"):
            print(f"{target} is out of date; regenerate it", file=sys.stderr)
            return 1
        print(f"{target} is up to date")
        return 0
    target.write_text(text.rstrip("\n") + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
